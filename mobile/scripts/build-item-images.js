// Connects item pictures to the game: `npm run images`.
//
// Drop a picture at assets/items/<category>/<item-id>.<jpg|jpeg|png|webp>
// (item ids are "<category>-<n>", e.g. assets/items/dog-breeds/dog-breeds-1.jpg)
// and run this script. It writes:
//   src/content/item-images.generated.ts – require() map the screens load
//   src/content/image-manifest.ts        – plain list of item ids that have a
//                                          picture; categories.ts uses it to
//                                          unlock a picture category
// The older animals/fruit pictures keep their manual map in item-images.ts.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const itemsDir = path.join(root, 'assets', 'items');
const EXTENSIONS = ['.webp', '.png', '.jpg', '.jpeg'];
const MAX_BYTES = 600 * 1024;

const found = [];
const warnings = [];
for (const category of fs.readdirSync(itemsDir, { withFileTypes: true })) {
  if (!category.isDirectory()) continue;
  const pattern = new RegExp(`^${category.name}-(\\d+)$`);
  const seen = new Set();
  for (const file of fs.readdirSync(path.join(itemsDir, category.name)).sort()) {
    const ext = path.extname(file).toLowerCase();
    const base = path.basename(file, path.extname(file));
    if (!EXTENSIONS.includes(ext) || !pattern.test(base)) continue;
    if (seen.has(base)) { warnings.push(`${category.name}/${file}: a second picture for ${base} – using the first`); continue; }
    seen.add(base);
    const size = fs.statSync(path.join(itemsDir, category.name, file)).size;
    if (size > MAX_BYTES) warnings.push(`${category.name}/${file}: ${Math.round(size / 1024)}KB – please shrink below ${MAX_BYTES / 1024}KB`);
    found.push({ id: base, category: category.name, file });
  }
}
found.sort((a, b) => a.category.localeCompare(b.category) || Number(a.id.split('-').pop()) - Number(b.id.split('-').pop()));

const header = '// Generated by scripts/build-item-images.js – do not edit; run `npm run images`.\n';
fs.writeFileSync(
  path.join(root, 'src', 'content', 'item-images.generated.ts'),
  header +
    "import type { ImageSourcePropType } from 'react-native';\n\n" +
    'export const GENERATED_ITEM_IMAGES: Record<string, ImageSourcePropType> = {\n' +
    found.map(({ id, category, file }) => `  '${id}': require('../../assets/items/${category}/${file}'),\n`).join('') +
    '};\n',
);
fs.writeFileSync(
  path.join(root, 'src', 'content', 'image-manifest.ts'),
  header +
    '// Item ids with a picture, without loading the pictures (safe under Node tests).\n' +
    'export const IMAGED_ITEM_IDS: readonly string[] = [\n' +
    found.map(({ id }) => `  '${id}',\n`).join('') +
    '];\n',
);

const perCategory = {};
for (const { category } of found) perCategory[category] = (perCategory[category] || 0) + 1;
console.log(`Connected ${found.length} pictures:`);
for (const [category, count] of Object.entries(perCategory)) console.log(`  ${category}: ${count}`);
for (const warning of warnings) console.warn(`  ! ${warning}`);
