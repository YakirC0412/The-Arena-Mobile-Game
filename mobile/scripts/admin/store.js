// Admin panel storage: reads and writes the game's real files (categories-data.json, assets/items, credits.json,
// image-sources.json) and keeps them consistent. Item n of a category is `<category>-<n>` everywhere, so deleting or
// moving an item renames its picture, original and credit too. Nothing is deleted: removed files go to archive/.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const { serialize } = require('./format');

const MOBILE = path.join(__dirname, '..', '..');
const REPO = path.join(MOBILE, '..');
const P = {
  data: path.join(MOBILE, 'src', 'content', 'categories-data.json'),
  items: path.join(MOBILE, 'assets', 'items'),
  credits: path.join(MOBILE, 'assets', 'items', 'credits.json'),
  sources: path.join(MOBILE, 'scripts', 'image-sources.json'),
  archive: path.join(REPO, 'archive'),
  skill: path.join(REPO, '.claude', 'skills', 'arena-images', 'scripts', 'arena_images.py'),
};
const EXT = ['.jpg', '.jpeg', '.png', '.webp', '.gif'];
const MIN_PICTURES = 30;
const LEVELS = ['easy', 'medium', 'hard'];
const STATUSES = ['active', 'reserve'];
const KINDS = ['photo', 'logo', 'product'];

class Bad extends Error {}
const bad = (message) => { throw new Bad(message); };

// ---- text helpers (same rules as the game: decision 18 and normalizeAnswer in engine.ts) ----
const stripGeresh = (s) => String(s ?? '').replace(/[׳'״"’‘`´]/g, '').replace(/\s+/g, ' ').trim();
const normalize = (s) => stripGeresh(s).normalize('NFKD').replace(/[֑-ׇ]/g, '').replace(/[.,!?()\-_/\\]/g, '')
  .replace(/\s+/g, ' ').trim().toLocaleLowerCase('he')
  .replace(/[םןךףץ]/g, (l) => ({ ם: 'מ', ן: 'נ', ך: 'כ', ף: 'פ', ץ: 'צ' })[l]);
const list = (v) => (Array.isArray(v) ? v : String(v ?? '').split(',')).map(stripGeresh).filter(Boolean);

// ---- files ----
const readData = () => JSON.parse(fs.readFileSync(P.data, 'utf8'));
const readCredits = () => (fs.existsSync(P.credits) ? JSON.parse(fs.readFileSync(P.credits, 'utf8')) : {});
function writeCredits(credits) {
  const key = (id) => [id.replace(/-\d+$/, ''), Number(id.split('-').pop())];
  const sorted = Object.fromEntries(Object.entries(credits).sort(([a], [b]) => {
    const [ca, na] = key(a), [cb, nb] = key(b);
    return ca < cb ? -1 : ca > cb ? 1 : na - nb;
  }));
  // The skill (Python on Windows) writes this file with CRLF line endings: keep whatever is there so git sees no churn.
  const eol = fs.existsSync(P.credits) && fs.readFileSync(P.credits, 'utf8').includes('\r\n') ? '\r\n' : '\n';
  fs.writeFileSync(P.credits, `${JSON.stringify(sorted, null, 1)}\n`.replace(/\n/g, eol));
}

// Skill input: every category with its English search names (the item's `en`, else its answer).
function writeSources(data) {
  const out = { _readme: 'Generated by the admin panel (npm run admin) from categories-data.json: edit categories there. Used by the arena-images skill; entry n = item <category>-<n>.' };
  for (const id of data.order) {
    const c = data.categories[id];
    if (!c.items.length) continue;
    out[id] = { ...(c.picture || { kind: 'photo' }), items: c.items.map((it) => it.en || it.answer) };
  }
  fs.writeFileSync(P.sources, `${JSON.stringify(out, null, 2)}\n`);
}
function writeData(data) {
  fs.writeFileSync(P.data, serialize(data));
  writeSources(data);
}

function rebuild() {
  const node = process.execPath;
  const run = (script) => cp.execFileSync(node, [path.join(MOBILE, 'scripts', script)], { cwd: MOBILE, encoding: 'utf8' });
  run('build-item-images.js');
  run('write-image-credits.js');
}

const dir = (cat) => path.join(P.items, cat);
function imageFile(cat, n) {
  for (const ext of EXT) {
    const file = path.join(dir(cat), `${cat}-${n}${ext}`);
    if (fs.existsSync(file)) return file;
  }
  return null;
}
const revealFile = (cat, n) => path.join(P.archive, 'reveal', cat, `${cat}-${n}.jpg`);
function toArchive(file, sub) {
  if (!file || !fs.existsSync(file)) return;
  const folder = path.join(P.archive, sub);
  fs.mkdirSync(folder, { recursive: true });
  fs.renameSync(file, path.join(folder, `${Date.now()}-${path.basename(file)}`));
}
function renameIfExists(from, to) { if (from && fs.existsSync(from)) fs.renameSync(from, to); }

// ---- validation ----
function getCategory(data, id) {
  return data.categories[id] ?? bad(`אין קטגוריה בשם ${id}`);
}
function getItem(category, n) {
  const i = Number(n) - 1;
  return category.items[i] ?? bad(`אין פריט מספר ${n}`);
}
function cleanItem(input, category, prev = {}) {
  const answer = stripGeresh(input.answer ?? prev.answer);
  if (!answer) bad('חסרה תשובה');
  const item = { answer };
  const aliases = [...new Set(list(input.aliases ?? prev.aliases))].filter((a) => normalize(a) !== normalize(answer));
  if (aliases.length) item.aliases = aliases;
  item.visual = String(input.visual ?? prev.visual ?? category.icon).trim() || category.icon;
  const en = String(input.en ?? prev.en ?? '').trim();
  if (en) item.en = en;
  const second = input.second !== undefined ? input.second : prev.second;
  if (second && stripGeresh(second.answer)) {
    item.second = { answer: stripGeresh(second.answer) };
    const sa = [...new Set(list(second.aliases))].filter((a) => normalize(a) !== normalize(second.answer));
    if (sa.length) item.second.aliases = sa;
  }
  return item;
}
function checkUnique(category, item, ignoreIndex) {
  const mine = [item.answer, ...(item.aliases || [])].map(normalize);
  category.items.forEach((other, i) => {
    if (i === ignoreIndex) return;
    for (const text of [other.answer, ...(other.aliases || [])].map(normalize)) {
      if (mine.includes(text)) bad(`התשובה "${text}" כבר קיימת בפריט "${other.answer}" באותה קטגוריה`);
    }
  });
}
function cleanPicture(p) {
  if (!p) return undefined;
  const out = { kind: KINDS.includes(p.kind) ? p.kind : 'photo' };
  if (p.hideName) out.hideName = true;
  if (p.anyLicense) out.anyLicense = true;
  const prefer = list(p.prefer);
  if (prefer.length) out.prefer = prefer;
  for (const k of ['query', 'prompt']) if (String(p[k] ?? '').trim()) out[k] = String(p[k]).trim();
  return out;
}
function cleanWays(ways) {
  const out = (Array.isArray(ways) ? ways : []).map((w) => [String(w[0] ?? '').trim(), w[1] !== false]).filter((w) => w[0]);
  if (out.length < 1 || out.length > 2) bad('צריך דרך משחק אחת או שתיים');
  return out;
}
function cleanCategory(input, prev = {}) {
  const c = {
    name: String(input.name ?? prev.name ?? '').trim(),
    icon: String(input.icon ?? prev.icon ?? '').trim() || '❓',
    level: input.level ?? prev.level ?? 'easy',
    status: input.status ?? prev.status ?? 'active',
    ways: cleanWays(input.ways ?? prev.ways),
  };
  if (!c.name) bad('חסר שם לקטגוריה');
  if (!LEVELS.includes(c.level)) bad('רמה לא תקינה');
  if (!STATUSES.includes(c.status)) bad('סטטוס לא תקין');
  const picture = cleanPicture(input.picture !== undefined ? input.picture : prev.picture);
  if (picture) c.picture = picture;
  return c;
}

// ---- reading for the page ----
function snapshot() {
  const data = readData();
  const credits = readCredits();
  const categories = {};
  for (const id of data.order) {
    const c = data.categories[id];
    let pictures = 0;
    const items = c.items.map((item, i) => {
      const n = i + 1;
      const file = imageFile(id, n);
      if (file) pictures += 1;
      const cr = credits[`${id}-${n}`] || {};
      return {
        n, ...item,
        pic: file ? { v: Math.round(fs.statSync(file).mtimeMs), hasOriginal: fs.existsSync(revealFile(id, n)) } : null,
        credit: file ? { via: cr.via, review: !!cr.review, needbox: !!cr.needbox, hidden: cr.hidden, license: cr.license, author: cr.author, source: cr.source } : null,
      };
    });
    categories[id] = { ...c, items, pictures, playable: pictures >= MIN_PICTURES && c.status === 'active' };
  }
  return { order: data.order, categories, min: MIN_PICTURES };
}

// ---- category operations ----
function createCategory(input) {
  const data = readData();
  const id = String(input.id ?? '').trim().toLowerCase();
  if (!/^[a-z][a-z0-9-]{1,40}$/.test(id)) bad('המזהה חייב להיות באנגלית קטנה, ספרות ומקפים בלבד (למשל: board-games)');
  if (data.categories[id]) bad('כבר יש קטגוריה עם המזהה הזה');
  data.categories[id] = { ...cleanCategory(input), items: [] };
  data.order.push(id);
  writeData(data);
  rebuild();
  return id;
}
function updateCategory(id, input) {
  const data = readData();
  const prev = getCategory(data, id);
  const { items } = prev;
  const next = cleanCategory(input, prev);
  if (input.picture === null) delete next.picture;
  data.categories[id] = { ...next, items };
  writeData(data);
  rebuild();
}
function deleteCategory(id) {
  const data = readData();
  getCategory(data, id);
  const stamp = Date.now();
  for (const [from, sub] of [[dir(id), 'deleted-categories'], [path.join(P.archive, 'reveal', id), 'deleted-categories']]) {
    if (fs.existsSync(from)) {
      fs.mkdirSync(path.join(P.archive, sub), { recursive: true });
      fs.renameSync(from, path.join(P.archive, sub, `${id}-${stamp}-${path.basename(path.dirname(from)) === 'reveal' ? 'reveal' : 'pictures'}`));
    }
  }
  const credits = readCredits();
  for (const key of Object.keys(credits)) if (key.replace(/-\d+$/, '') === id) delete credits[key];
  writeCredits(credits);
  delete data.categories[id];
  data.order = data.order.filter((x) => x !== id);
  writeData(data);
  rebuild();
}
function moveCategory(id, dir) {
  const data = readData();
  const i = data.order.indexOf(id);
  if (i < 0) bad('אין קטגוריה כזו');
  const j = i + (Number(dir) < 0 ? -1 : 1);
  if (j < 0 || j >= data.order.length) return;
  [data.order[i], data.order[j]] = [data.order[j], data.order[i]];
  writeData(data);
}

// ---- item operations ----
function addItem(cat, input) {
  const data = readData();
  const category = getCategory(data, cat);
  const item = cleanItem(input, category);
  checkUnique(category, item, -1);
  category.items.push(item);
  writeData(data);
  return category.items.length;
}
function updateItem(cat, n, input) {
  const data = readData();
  const category = getCategory(data, cat);
  const prev = getItem(category, n);
  const item = cleanItem(input, category, prev);
  checkUnique(category, item, Number(n) - 1);
  category.items[Number(n) - 1] = item;
  writeData(data);
}
function deleteItem(cat, n) {
  const data = readData();
  const category = getCategory(data, cat);
  getItem(category, n);
  const total = category.items.length, k = Number(n);
  const credits = readCredits();
  toArchive(imageFile(cat, k), 'replaced-images');
  toArchive(revealFile(cat, k), 'replaced-images');
  delete credits[`${cat}-${k}`];
  for (let i = k + 1; i <= total; i += 1) {
    const file = imageFile(cat, i);
    if (file) fs.renameSync(file, path.join(dir(cat), `${cat}-${i - 1}${path.extname(file)}`));
    renameIfExists(revealFile(cat, i), revealFile(cat, i - 1));
    if (credits[`${cat}-${i}`]) { credits[`${cat}-${i - 1}`] = credits[`${cat}-${i}`]; delete credits[`${cat}-${i}`]; }
  }
  category.items.splice(k - 1, 1);
  writeCredits(credits);
  writeData(data);
  rebuild();
}
function moveItem(cat, n, delta) {
  const data = readData();
  const category = getCategory(data, cat);
  getItem(category, n);
  const a = Number(n), b = a + (Number(delta) < 0 ? -1 : 1);
  if (b < 1 || b > category.items.length) return;
  [category.items[a - 1], category.items[b - 1]] = [category.items[b - 1], category.items[a - 1]];
  const credits = readCredits();
  const ka = `${cat}-${a}`, kb = `${cat}-${b}`;
  const [ca, cb] = [credits[ka], credits[kb]];
  delete credits[ka]; delete credits[kb];
  if (cb) credits[ka] = cb;
  if (ca) credits[kb] = ca;
  const fa = imageFile(cat, a), fb = imageFile(cat, b), tmp = path.join(dir(cat), `.swap-${Date.now()}`);
  if (fa) fs.renameSync(fa, tmp);
  if (fb) fs.renameSync(fb, path.join(dir(cat), `${cat}-${a}${path.extname(fb)}`));
  if (fa) fs.renameSync(tmp, path.join(dir(cat), `${cat}-${b}${path.extname(fa)}`));
  const [ra, rb, rt] = [revealFile(cat, a), revealFile(cat, b), `${revealFile(cat, a)}.swap`];
  renameIfExists(ra, rt);
  renameIfExists(rb, ra);
  renameIfExists(rt, rb);
  writeCredits(credits);
  writeData(data);
  rebuild();
}

// ---- picture operations that need no Python ----
function restoreOriginal(cat, n) {
  const data = readData();
  const category = getCategory(data, cat);
  getItem(category, n);
  const rev = revealFile(cat, n);
  if (!fs.existsSync(rev)) bad('אין עותק מקורי לשחזור');
  const cur = imageFile(cat, n);
  if (cur) fs.rmSync(cur);
  fs.copyFileSync(rev, path.join(dir(cat), `${cat}-${n}.jpg`));
  const credits = readCredits();
  const cr = credits[`${cat}-${n}`] || {};
  delete cr.hidden; delete cr.blur; delete cr.crop;
  if (category.picture?.hideName) cr.needbox = true;
  credits[`${cat}-${n}`] = cr;
  writeCredits(credits);
  rebuild();
}

// ---- the Python skill (search, AI, upload, blur): one run at a time ----
function pythonPath() {
  if (process.env.ARENA_PYTHON) return process.env.ARENA_PYTHON;
  const local = path.join(process.env.LOCALAPPDATA || '', 'Programs', 'Python', 'Python312', 'python.exe');
  return fs.existsSync(local) ? local : 'python';
}
function runSkill(args) {
  return new Promise((resolve) => {
    const child = cp.spawn(pythonPath(), ['-P', P.skill, ...args], { cwd: REPO, env: { ...process.env, PYTHONIOENCODING: 'utf-8' } });
    let out = '';
    child.stdout.on('data', (d) => { out += d; });
    child.stderr.on('data', (d) => { out += d; });
    const timer = setTimeout(() => child.kill(), 5 * 60 * 1000);
    child.on('error', (e) => { clearTimeout(timer); resolve({ ok: false, lines: [`לא הצלחתי להפעיל את Python: ${e.message}`] }); });
    child.on('close', (code) => {
      clearTimeout(timer);
      const lines = out.split(/\r?\n/).filter((l) => l && !/^\s/.test(l) && !/^(Wrote |SHEET |GRID )/.test(l));
      resolve({ ok: code === 0 && !lines.some((l) => /^(FAIL|Traceback)/.test(l)), lines });
    });
  });
}

